function names = available_benchmarks(group)
%AVAILABLE_BENCHMARKS Curated SCIS benchmark groups.
all_names = { ...
    'heat1d', ...
    'massspring', ...
    'rcbuilding', ...
    'networkdiffusion', ...
    'advectiondiffusion1d', ...
    'flexiblebeam', ...
    'cstrlinear', ...
    'aircraftpitch', ...
    'powergrid', ...
    'hvacmultizone'};

if nargin < 1
    group = 'all';
end

switch lower(group)
    case {'all','scis10'}
        names = all_names;
    case 'small'
        names = {'heat1d','massspring','rcbuilding','aircraftpitch'};
    case 'pde'
        names = {'heat1d','advectiondiffusion1d','networkdiffusion','flexiblebeam'};
    case 'large'
        names = {'powergrid','hvacmultizone','rcbuilding','networkdiffusion'};
    otherwise
        error('Unknown benchmark group: %s', group);
end
end
