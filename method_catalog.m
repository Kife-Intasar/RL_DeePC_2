function catalog = method_catalog()
%METHOD_CATALOG Metadata for the SCIS DeePC package.
catalog = struct([]);
entries = { ...
    'full_deepc','baseline','Full DeePC baseline with the standard formulation',false; ...
    'robust_full_deepc','baseline','Robust full DeePC baseline with tightened regularization',false; ...
    'svd_deepc','baseline','SVD-reduced DeePC baseline with the standard formulation',false; ...
    'robust_svd_deepc','baseline','Robust SVD-reduced DeePC baseline with tightened regularization',false; ...
    'iv_deepc','baseline','IV-DeePC / CL-SPC-style direct predictor baseline',false; ...
    'gamma_ddpc','baseline','gamma-DDPC-style two-stage DeePC baseline',false; ...
    'replacement_deepc','baseline','Paper-style online DeePC with replacement updates',false; ...
    'adding_deepc','baseline','Paper-style online DeePC with additive SVD updates',false; ...
    'online_reduced_order_deepc','baseline','Paper-style selective online reduced-order DeePC',false; ...
    'arx_mpc','baseline','ARX-MPC baseline',false; ...
    'fir_mpc','baseline','FIR-MPC baseline',false; ...
    'era_mpc','baseline','Data-driven ERA-MPC baseline',false; ...
    'nominal_bt_mpc','baseline','Nominal model-based BT-MPC baseline',false; ...
    'proposed_bt_deepc','proposed','Proposed BT-informed fast projector DeePC',true; ...
    'proposed_bt_reduced_deepc','proposed','Proposed BT-informed reduced-variable DeePC',true; ...
    'proposed_irka_deepc','proposed','Proposed IRKA-informed fast projector DeePC',true; ...
    'proposed_irka_reduced_deepc','proposed','Proposed IRKA-informed reduced-variable DeePC',true};
for i = 1:size(entries,1)
    catalog(i).name = entries{i,1}; %#ok<AGROW>
    catalog(i).group = entries{i,2}; %#ok<AGROW>
    catalog(i).description = entries{i,3}; %#ok<AGROW>
    catalog(i).is_proposed = entries{i,4}; %#ok<AGROW>
end
end
